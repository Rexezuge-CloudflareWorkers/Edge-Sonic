import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { KIT_DEDUPE } from '@rexezuge/tooling/vitest';
import path from 'node:path';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const apiGeneratedDir = path.resolve(__dirname, '../../apps/api/src/generated');
const apiSpaShellPath = path.resolve(apiGeneratedDir, 'spa-shell.ts');

const apiTarget = 'http://localhost:8787';

export default defineConfig({
  // One React for the app and for `@rexezuge/web`. A peer is not installed twice
  // under a registry install, so the two sides already agree there; a `link:`
  // install gives the symlinked package its own `node_modules`, and the SPA would
  // then bundle two Reacts — every hook in a kit component reads a dispatcher the
  // app's copy never initialised.
  resolve: { dedupe: [...KIT_DEDUPE] },
  plugins: [
    react(),
    tailwindcss(),
    {
      name: 'spa-shell-embed',
      closeBundle() {
        const indexPath = path.resolve(__dirname, 'dist/index.html');
        if (!existsSync(indexPath)) {
          console.warn('spa-shell-embed: dist/index.html not found, skipping');
          return;
        }
        const html: string = readFileSync(indexPath, 'utf8');
        const output: string = `// Auto-generated by Vite build plugin - DO NOT EDIT.\nexport const SPA_HTML: string = ${JSON.stringify(html)};\n`;
        if (!existsSync(apiGeneratedDir)) {
          mkdirSync(apiGeneratedDir, { recursive: true });
        }
        writeFileSync(apiSpaShellPath, output);
      },
    },
  ],
  server: {
    proxy: {
      // Dev only: the SPA is served same-origin in production, so every API path
      // is root-relative and there is no base URL to configure.
      '/user': { target: apiTarget, changeOrigin: true },
      '/rest': { target: apiTarget, changeOrigin: true },
      '/health': { target: apiTarget, changeOrigin: true },
    },
  },
  build: {
    outDir: 'dist',
    emptyOutDir: true,
  },
});
